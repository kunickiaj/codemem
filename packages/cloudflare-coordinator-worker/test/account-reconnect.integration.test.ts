import type { D1Database } from '@cloudflare/workers-types';
import { env } from 'cloudflare:workers';
import { expect,it } from 'vitest';
import { D1CoordinatorStore } from '../../core/src/d1-coordinator-store.js';
import type { AuthLinkBackend } from '../../core/src/coordinator-auth-link.js';
import { reconnectFixture } from './account-reconnect-fixture.js';
import { config,input,hash,NOW } from './account-change-fixture.js';

it('native D1 reconnects A-B-A with one original claim, one CAS winner and rollback',async () => {
	const db = (env as unknown as {COORDINATOR_DB:D1Database}).COORDINATOR_DB;
	const backend: AuthLinkBackend = {first: ({sql,values}) => db.prepare(sql).bind(...values).first(),run:async ({sql,values}) => (await db.prepare(sql).bind(...values).run()).meta.changes,batch:async (statements) => (await db.batch(statements.map(({sql,values}) => db.prepare(sql).bind(...values)))).map((r) => r.meta.changes)};
	const f = await reconnectFixture(new D1CoordinatorStore(db,{authClock:() => NOW}),backend);
	const rows = async (table: string) => (await db.prepare(`SELECT * FROM ${table}`).all()).results;
	const claims = await rows('coordinator_auth_device_claims');
	const ownership = await rows('coordinator_device_ownership_bindings'),grants = await rows('coordinator_identity_group_grants');
	const genesis = (await rows('coordinator_auth_account_links'))[0];
	await f.disconnect(1);
	expect(await f.status.readAuthDeviceClaimReadiness({signer:input.signer,identityId:input.identityId},config)).toMatchObject({kind:'eligible',authority:'device_claim'});
	expect(await f.status.readAccountLinkStatus(input.signer,config,{identityId:input.identityId})).toMatchObject({state:'unlinked',account:null});
	const one = await f.confirmed(1,'account-B'),two = await f.confirmed(2,'account-B');
	const outcomes = await Promise.all([f.links.finalizeAuthLinkAttempt(one.proof,config),f.links.finalizeAuthLinkAttempt(two.proof,config)]);
	expect(outcomes.filter((r) => r.kind === 'applied')).toHaveLength(1);
	expect(outcomes.filter((r) => r.kind === 'rejected')).toHaveLength(1);
	const winner = outcomes[0]?.kind === 'applied' ? one : two,stale = winner === one ? two : one;
	expect(await f.sessions.redeemAuthLinkSessionWithBrowserTransaction({...winner.pins,binderHash:winner.binderHash,credentialHash:hash(4001)},f.bc)).toMatchObject({kind:'issued'});
	const middle = (await rows('coordinator_auth_account_links'))[0];
	await f.disconnect(2,'account-B');
	expect((await rows('coordinator_auth_account_connection_history')).find((h) => h.link_id === middle?.link_id)).toMatchObject({signin_floor:middle?.signin_floor});
	expect(await f.links.finalizeAuthLinkAttempt(stale.proof,config)).toMatchObject({kind:'rejected'});
	expect(await f.links.finalizeAuthLinkAttempt(winner.proof,config)).toMatchObject({kind:'existing'});
	const last = await f.confirmed(3,'account-A');
	await db.prepare("CREATE TRIGGER fail_relink_successor BEFORE UPDATE ON coordinator_auth_account_connection_history WHEN NEW.successor_link_id IS NOT OLD.successor_link_id BEGIN SELECT RAISE(ABORT,'injected'); END").run();
	await expect(f.links.finalizeAuthLinkAttempt(last.proof,config)).rejects.toThrow();
	expect(await rows('coordinator_auth_account_links')).toEqual([]);
	expect(await rows('coordinator_auth_device_claims')).toEqual(claims);
	expect((await rows('coordinator_auth_account_connection_history')).find((h) => h.link_id === middle?.link_id)).toMatchObject({successor_link_id:null});
	await db.prepare('DROP TRIGGER fail_relink_successor').run();
	expect(await f.links.finalizeAuthLinkAttempt(last.proof,config)).toMatchObject({kind:'applied'});
	const current = (await rows('coordinator_auth_account_links'))[0];
	expect(new Set([genesis?.link_id,middle?.link_id,current?.link_id]).size).toBe(3);
	const signedIn = await f.signin(1),sessionsBefore = await rows('coordinator_auth_sessions');
	expect(await f.sessions.preserveAuthLinkSessionCompletion({...last.pins,binderHash:last.binderHash,credentialHash:signedIn.credentialHash},f.bc)).toEqual({kind:'preserved'});
	expect(await rows('coordinator_auth_sessions')).toEqual(sessionsBefore);
	expect(await f.profiles.readAuthSessionAccount(signedIn.credentialHash,config)).toMatchObject({profile:{displayName:'account-A'}});
	expect(await rows('coordinator_auth_device_claims')).toEqual(claims);
	expect(await rows('coordinator_device_ownership_bindings')).toEqual(ownership);
	expect(await rows('coordinator_identity_group_grants')).toEqual(grants);
});
