import { readinessInvalidation } from "./coordinator-readiness-invalidation.js";
/**
 * What a removal writes beyond the tombstone and the enrollment, as statements
 * for the removal's own transaction or batch. Every statement finds its rows
 * through the tombstones this removal wrote, so a removal that wrote none
 * changes nothing here. They run after the enrollment delete, because whether a
 * device ID has an enrollment left decides which memberships go.
 */

export interface RemovalDependentStatement {
	sql: string;
	values: (string | number | null)[];
	read?: boolean;
}

/**
 * The condition that selects the tombstones of this removal, for the alias `t`
 * of `coordinator_device_removals`, with its bound values.
 */
export interface OwnTombstones {
	sql: string;
	values: (string | number | null)[];
}

/** The actor type of a membership revocation that a removal made. */
export const DEVICE_REMOVAL_ACTOR_TYPE = "device_removal";

/**
 * For a membership `m` and a tombstone `t` of its device ID: the scope belongs
 * to the group the device was removed from, or the device ID has no enrollment
 * left in any group. A scope names its group in its own row. A scope without a
 * group, and a membership whose scope row is missing, match only the second.
 */
const MEMBERSHIP_OF_REMOVED_SQL = `(t.group_id = (SELECT s.group_id FROM coordinator_scopes s
    WHERE s.scope_id = m.scope_id)
  OR NOT EXISTS (SELECT 1 FROM enrolled_devices e WHERE e.device_id = m.device_id))`;

/**
 * The removal UUID is generated by the store inside this operation. A caller
 * cannot reserve its receipt ID in advance using a membership revocation.
 */
const effectIdSql = (removalId: string, seq: string, membership: string) =>
	`'device-removal:' || ${removalId} || ':' || ${seq} || ':' || ${membership}.rowid`;

/**
 * One receipt for each active membership the removal revokes, written before the
 * revocation with the values the membership will have after it. The request text
 * has the keys and the form of the membership revocation's own.
 */
function receiptStatement(
	own: OwnTombstones,
	actorId: string | null,
	now: string,
): RemovalDependentStatement {
	return {
		sql: `INSERT INTO coordinator_scope_membership_effect_receipts(
  effect_id, action, request_json, outcome_applied, scope_id, device_id, role, status,
  membership_epoch, coordinator_id, group_id, manifest_issuer_device_id, manifest_hash,
  signed_manifest_json, updated_at, created_at)
SELECT ${effectIdSql("MIN(t.removal_id)", "MIN(t.removal_seq)", "m")}, 'revoke',
  json_object('scopeId', m.scope_id, 'deviceId', m.device_id, 'groupId', NULL,
    'membershipEpoch', NULL, 'manifestHash', NULL, 'signedManifestJson', NULL,
    'actorType', '${DEVICE_REMOVAL_ACTOR_TYPE}', 'actorId', ?),
  1, m.scope_id, m.device_id, m.role, 'revoked', m.membership_epoch + 1, m.coordinator_id,
  m.group_id, m.manifest_issuer_device_id, m.manifest_hash, m.signed_manifest_json, ?, ?
FROM coordinator_device_removals t
JOIN coordinator_scope_memberships m ON m.device_id = t.device_id AND m.status = 'active'
WHERE ${own.sql} AND ${MEMBERSHIP_OF_REMOVED_SQL}
GROUP BY m.rowid`,
		values: [actorId, now, now, ...own.values],
	};
}

/** A receipt of this removal, joined to the membership `m` and tombstone `t` it names. */
const OWN_RECEIPT_JOIN_SQL = `JOIN coordinator_scope_membership_effect_receipts r
  ON r.effect_id = ${effectIdSql("t.removal_id", "t.removal_seq", "m")}`;

/** One audit row for each receipt, with the membership's state before the revocation. */
function auditStatement(own: OwnTombstones, actorId: string | null): RemovalDependentStatement {
	return {
		sql: `INSERT INTO coordinator_scope_membership_audit_log(
  effect_id, action, scope_id, device_id, role, status, membership_epoch, previous_role,
  previous_status, previous_membership_epoch, coordinator_id, group_id, actor_type, actor_id,
  manifest_hash, created_at)
SELECT r.effect_id, 'revoke', r.scope_id, r.device_id, r.role, r.status, r.membership_epoch,
  m.role, m.status, m.membership_epoch, r.coordinator_id, r.group_id,
  '${DEVICE_REMOVAL_ACTOR_TYPE}', ?, r.manifest_hash, r.created_at
FROM coordinator_device_removals t
JOIN coordinator_scope_memberships m ON m.device_id = t.device_id AND m.status = 'active'
${OWN_RECEIPT_JOIN_SQL}
WHERE ${own.sql}`,
		values: [actorId, ...own.values],
	};
}

/** The revocation itself: the epoch advances by one, as it does without a supplied epoch. */
function membershipStatement(own: OwnTombstones, now: string): RemovalDependentStatement {
	return {
		sql: `UPDATE coordinator_scope_memberships AS m
SET status = 'revoked', membership_epoch = membership_epoch + 1, updated_at = ?
WHERE m.status = 'active' AND EXISTS (SELECT 1 FROM coordinator_device_removals t
  ${OWN_RECEIPT_JOIN_SQL}
  WHERE ${own.sql} AND t.device_id = m.device_id)`,
		values: [now, ...own.values],
	};
}

const GRANT_OF_REMOVED_SQL = `g.revoked_at IS NULL AND g.group_id = t.group_id
  AND t.device_id IN (g.seed_device_id, g.worker_device_id)`;

/** Every unrevoked grant that names the device as seed or worker in a group it left. */
function grantStatement(own: OwnTombstones, now: string): RemovalDependentStatement {
	return {
		sql: `UPDATE coordinator_bootstrap_grants AS g SET revoked_at = ?
WHERE EXISTS (SELECT 1 FROM coordinator_device_removals t
  WHERE ${own.sql} AND ${GRANT_OF_REMOVED_SQL})`,
		values: [now, ...own.values],
	};
}

const REQUEST_OF_REMOVED_SQL = "j.status = 'pending' AND j.device_id = t.device_id";

/** Every pending join request of a removed device ID, in any group. */
function joinRequestStatement(
	own: OwnTombstones,
	actorId: string | null,
	now: string,
): RemovalDependentStatement {
	return {
		sql: `UPDATE coordinator_join_requests AS j
SET status = 'denied', reviewed_at = ?, reviewed_by = ?
WHERE EXISTS (SELECT 1 FROM coordinator_device_removals t
  WHERE ${own.sql} AND ${REQUEST_OF_REMOVED_SQL})`,
		values: [now, actorId, ...own.values],
	};
}

/**
 * A read in the same transaction or batch. It raises when this removal wrote a
 * tombstone and one of the writes above left a row behind, because a trigger
 * suppressed that write without an error. The whole removal then rolls back.
 */
function completeStatement(own: OwnTombstones): RemovalDependentStatement {
	return {
		sql: `SELECT CASE WHEN EXISTS (SELECT 1 FROM coordinator_device_removals t WHERE ${own.sql} AND (
  EXISTS (SELECT 1 FROM coordinator_scope_memberships m
    WHERE m.device_id = t.device_id AND m.status = 'active' AND ${MEMBERSHIP_OF_REMOVED_SQL})
  OR EXISTS (SELECT 1 FROM coordinator_scope_memberships m ${OWN_RECEIPT_JOIN_SQL}
    WHERE m.device_id = t.device_id AND NOT EXISTS (
      SELECT 1 FROM coordinator_scope_membership_audit_log a WHERE a.effect_id = r.effect_id))
  OR EXISTS (SELECT 1 FROM coordinator_bootstrap_grants g WHERE ${GRANT_OF_REMOVED_SQL})
  OR EXISTS (SELECT 1 FROM coordinator_join_requests j WHERE ${REQUEST_OF_REMOVED_SQL})))
THEN json('device_removal_incomplete') ELSE 1 END AS complete`,
		values: own.values,
		read: true,
	};
}

export interface RemovalDependents {
	/** Receipts, audit rows, memberships, bootstrap grants and join requests, in that order. */
	writes: RemovalDependentStatement[];
	complete: RemovalDependentStatement;
	/** Empty before migration 0056 adds `groups.readiness_generation`. */
	invalidate: RemovalDependentStatement[];
}

export function removalDependentStatements(
	own: OwnTombstones,
	removal: { actorId: string | null; now: string; readiness: boolean },
): RemovalDependents {
	const { actorId, now } = removal;
	return {
		writes: [
			receiptStatement(own, actorId, now),
			auditStatement(own, actorId),
			membershipStatement(own, now),
			grantStatement(own, now),
			joinRequestStatement(own, actorId, now),
		],
		complete: completeStatement(own),
		// A last enrollment can revoke memberships outside its tombstone group.
		// The receipt identifies the scope, whose group may have changed since the grant.
		invalidate: readinessInvalidation(removal.readiness, {
			sql: `UPDATE groups SET readiness_generation=NULL WHERE readiness_generation IS NOT NULL AND group_id IN (
 SELECT t.group_id FROM coordinator_device_removals t WHERE ${own.sql}
 UNION ALL
 SELECT s.group_id FROM coordinator_device_removals t
 JOIN coordinator_scope_memberships m ON m.device_id=t.device_id
 ${OWN_RECEIPT_JOIN_SQL}
 JOIN coordinator_scopes s ON s.scope_id=r.scope_id
 WHERE ${own.sql})`,
			values: [...own.values, ...own.values],
		}),
	};
}

/** True when each revoked membership has its receipt and its audit row. */
export function membershipRevocationsMatch(changes: readonly number[]): boolean {
	const [receipts, audits, memberships] = changes;
	return receipts === audits && audits === memberships;
}
